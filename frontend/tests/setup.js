// Vitest global setup
import "@testing-library/jest-dom/vitest";

// jsdom does not implement matchMedia; ThemeContext and reduced-motion checks need it.
if (typeof window !== "undefined" && !window.matchMedia) {
  window.matchMedia = (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  });
}
